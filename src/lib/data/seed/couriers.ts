import type { Courier, CourierTariff } from '@/types';

const UPDATED = '2026-06-10';

function tariff(
  courierId: string,
  index: number,
  overrides: Omit<CourierTariff, 'id' | 'courierId' | 'effectiveFrom' | 'updatedAt'> &
    Partial<Pick<CourierTariff, 'effectiveFrom' | 'updatedAt'>>,
): CourierTariff {
  return {
    id: `${courierId}_tariff_${index}`,
    courierId,
    effectiveFrom: '2026-01-01',
    updatedAt: UPDATED,
    ...overrides,
  };
}

